test('engine telemetry captures real frames, vehicle collisions and blueprint actions',()=>{
 resetEngineDiagnostics('3d');
 tickEngineDiagnostics(1/60);tickEngineDiagnostics(.05);
 recordEngineEvent('vehicle-enter','Jeep');
 recordEngineEvent('collision','Wall');
 recordEngineEvent('blueprint','Test Walk');
 recordEngineWarning('Physics fallback used');
 const report=engineDiagnosticReport({genre:'fieldlab',entityCount:12,blueprintGlobals:{labWalk:1,labInteract:1,labDrive:0,labCompleted:0}});
 assert.equal(report.frames,2);
 assert.equal(report.vehicleEntries,1);
 assert.equal(report.collisions,1);
 assert.equal(report.blueprintActions,1);
 assert.equal(report.slowFrames,1);
 assert.equal(report.fieldLab.walk,true);
 assert.equal(report.fieldLab.driving,false);
 assert.equal(report.fieldLab.collisionsVerified,false);
 assert.equal(report.warnings.length,1);
 stopEngineDiagnostics();tickEngineDiagnostics(1/60);assert.equal(engineDiagnostics.frames,2);
});
test('diagnostics bound event logs, sanitize globals and return independent snapshots',()=>{
 resetEngineDiagnostics('2d');
 for(let i=0;i<110;i++)recordEngineEvent('blueprint','test');
 const a=engineDiagnosticReport({blueprintGlobals:{gold:5,internal:{secret:true}}});
 assert.equal(a.events.length,80);
 assert.equal(a.globals.gold,5);
 assert.equal('internal' in a.globals,false);
 a.events[0].type='modified';
 assert.notEqual(engineDiagnosticReport().events[0].type,'modified');
});
test('conditional enter gate activates when vehicle state changes while inside',()=>{
 resetSequences();resetEngineDiagnostics('3d');
 const player={id:100,x:100,y:100,w:32,h:32,_hiddenInVehicle:false};
 const gate={id:1,x:100,y:100,w:32,h:32,sequence:{...newSequence(),event:'enter',once:true,conditions:[{type:'playerInVehicle'}],instructions:[{type:'setVariable',key:'labDrive',value:1}]}};
 const ctx={playing:true,entities:[gate,player],player,keys:new Set()};
 updateSequences(.016,ctx);assert.equal(sequenceRuntime.globals.labDrive,undefined);
 player._hiddenInVehicle=true;
 updateSequences(.016,ctx);assert.equal(sequenceRuntime.globals.labDrive,1);
 updateSequences(.016,ctx);assert.equal(engineDiagnostics.blueprintActions,1);
 stopEngineDiagnostics();
});
test('mounting vehicle consumes E so nearby Blueprints cannot fire at same time',()=>{
 resetSequences();
 const player={id:100,x:100,y:100,w:32,h:32,_vehicleInputConsumed:true};
 const button={id:1,x:100,y:100,w:32,h:32,sequence:{...newSequence(),event:'interact',instructions:[{type:'setVariable',key:'money',value:500}]}};
 const ctx={playing:true,entities:[button,player],player,keys:new Set(['e'])};
 updateSequences(.016,ctx);
 assert.equal(sequenceRuntime.globals.money,undefined);
 ctx.keys.clear();updateSequences(.016,ctx);
 player._vehicleInputConsumed=false;ctx.keys.add('e');updateSequences(.016,ctx);
 assert.equal(sequenceRuntime.globals.money,500);
});
